#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import {
  detectTestCommand,
  ensureDir,
  fileNeedsCodeValidation,
  fileNeedsDocsReview,
  getBranch,
  getGitStatus,
  isBinaryAsset,
  isDocsFile,
  isLocalOnly,
  readJson,
  repoRoot,
  run,
  runGit,
  sanitizeForList,
  timestamp,
  uniqueFilePath,
  writeJson,
} from "./lib.mjs";

const root = repoRoot();
const branch = getBranch(root);
const baselinePath = path.join(root, ".codex", "state", "session-baseline.json");
const baseline = readJson(baselinePath, null);
const baselineDirty = new Set(baseline?.dirtyFiles ?? []);

const status = getGitStatus(root).filter((entry) => !isLocalOnly(entry.path));
const currentFiles = status.map((entry) => entry.path);
const deletions = status.filter((entry) => entry.status.includes("D"));
const rawCandidates = status
  .map((entry) => entry.path)
  .filter((relPath) => !baselineDirty.has(relPath))
  .filter((relPath) => relPath !== "docs/CODEX_CHANGELOG.md");

const binarySkipped = rawCandidates.filter((relPath) => isBinaryAsset(relPath));
let candidates = rawCandidates.filter((relPath) => !isBinaryAsset(relPath));

if (!currentFiles.length) {
  console.log("[codex-hooks] No repository changes detected.");
  process.exit(0);
}

const validation = runValidation(candidates);
const intakeFiles = createRealEstateIntakes(rawCandidates);
candidates = [...new Set([...candidates, ...intakeFiles])].sort();

const docsTouched = candidates.some((relPath) => isDocsFile(relPath));
const docsReviewNeeded = candidates.some((relPath) => fileNeedsDocsReview(relPath));
const docsPending = docsReviewNeeded && !docsTouched;

const changelogPath = updateChangelog({
  binarySkipped,
  branch,
  candidates,
  deletions: deletions.map((entry) => entry.path),
  docsPending,
  intakeFiles,
  skippedBaseline: [...baselineDirty].filter((relPath) => currentFiles.includes(relPath)),
  validation,
});
candidates = [...new Set([...candidates, changelogPath])].sort();

const commitResult = maybeCommit({
  baseline,
  branch,
  candidates,
  deletions,
  validation,
});

writeJson(path.join(root, ".codex", "state", "last-quality-gate.json"), {
  branch,
  candidates,
  commitResult,
  finishedAt: new Date().toISOString(),
  validation,
});

if (!validation.ok) {
  process.exit(validation.status || 1);
}

process.exit(0);

function runValidation(files) {
  const codeFiles = files.filter((relPath) => fileNeedsCodeValidation(relPath));
  if (!codeFiles.length) {
    return {
      command: "not run",
      ok: true,
      reason: "no code, config, migration, or script changes detected",
      status: 0,
    };
  }

  const testCommand = detectTestCommand(root);
  if (!testCommand) {
    return {
      command: "not detected",
      ok: false,
      reason: "no test or lint command detected",
      status: 1,
    };
  }

  console.log(`[codex-hooks] Running validation: ${testCommand.label}`);
  const result = run(testCommand.command, testCommand.args, {
    cwd: root,
    maxBuffer: 1024 * 1024 * 32,
  });

  if (result.stdout.trim()) process.stdout.write(result.stdout);
  if (result.stderr.trim()) process.stderr.write(result.stderr);

  return {
    command: testCommand.label,
    ok: result.ok,
    reason: result.ok ? "passed" : "failed",
    status: result.status,
  };
}

function createRealEstateIntakes(files) {
  const assets = files.filter((relPath) => isRealEstateAsset(relPath));
  if (!assets.length) return [];

  const dir = path.join(root, "docs", "imobiliaria", "pendencias");
  ensureDir(dir);

  const target = uniqueFilePath(
    path.join(dir, `${timestamp()}-disponibilidade-imobiliaria.md`),
  );

  const content = `# Intake disponibilidade imobiliaria

Generated by \`.codex/hooks/stop-quality-gate.mjs\`.

## Arquivos adicionados ou alterados

${sanitizeForList(assets)}

## Fluxo de extracao

1. Ler cada PDF/imagem e extrair apenas informacoes visiveis.
2. Organizar o resultado em Markdown copiavel usando secoes por empreendimento, unidade ou item.
3. Omitir campos sem informacao em vez de preencher com vazio, "N/A" ou placeholders.
4. Consolidar duvidas, valores ilegiveis e informacoes faltantes ao final em "Pendencias".
5. Quando houver texto extraido em JSON ou pares campo/valor, usar:

\`\`\`bash
node scripts/organize-real-estate-availability.mjs --input <arquivo-extraido> --output docs/imobiliaria/outputs/<nome>.md
\`\`\`

## Pendencias

- Extrair dados dos arquivos listados.
- Conferir se valores, disponibilidade, unidade e contato estao legiveis.
`;

  fs.writeFileSync(target, content, "utf8");
  return [path.relative(root, target).replace(/\\/g, "/")];
}

function isRealEstateAsset(relPath) {
  if (!isBinaryAsset(relPath)) return false;

  const normalized = relPath
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{Diacritic}/gu, "");

  return [
    "imobiliaria",
    "imovel",
    "imoveis",
    "disponibilidade",
    "availability",
    "real-estate",
    "real_estate",
    "tabela",
    "unidade",
  ].some((keyword) => normalized.includes(keyword));
}

function updateChangelog({
  binarySkipped,
  branch,
  candidates,
  deletions,
  docsPending,
  intakeFiles,
  skippedBaseline,
  validation,
}) {
  const relPath = "docs/CODEX_CHANGELOG.md";
  const changelog = path.join(root, relPath);
  ensureDir(path.dirname(changelog));

  const existing = fs.existsSync(changelog)
    ? fs.readFileSync(changelog, "utf8")
    : "# Codex Technical Change Log\n\nThis file is maintained by project-local Codex hooks.\n";

  const entry = `\n## ${new Date().toISOString()} - ${branch || "detached"}\n\n` +
    `Objective: ${inferObjective(candidates)}\n\n` +
    `Files changed:\n${sanitizeForList(candidates)}\n\n` +
    `Impact: ${inferImpact(candidates)}\n\n` +
    `Risk: ${inferRisk(candidates, deletions)}\n\n` +
    `Validation: \`${validation.command}\` - ${validation.reason}\n\n` +
    `Documentation: ${docsPending ? "review recommended for README/docs because business, script, model, or migration files changed" : "covered by changed files or not required"}\n\n` +
    `Generated real estate intake files:\n${sanitizeForList(intakeFiles)}\n\n` +
    `Skipped from auto-commit because they were dirty before the turn:\n${sanitizeForList(skippedBaseline)}\n\n` +
    `Skipped binary/PDF assets from auto-commit:\n${sanitizeForList(binarySkipped)}\n\n` +
    `Rollback: restore listed files from Git or from local snapshots in \`.codex/backups\`; after an automatic commit, use \`git revert <commit>\`.\n`;

  const next = existing.includes("\n## ")
    ? existing.replace(/\n## /, `${entry}\n## `)
    : `${existing.trimEnd()}\n${entry}\n`;

  fs.writeFileSync(changelog, next, "utf8");
  return relPath;
}

function inferObjective(files) {
  if (files.some((relPath) => relPath.startsWith(".codex/"))) {
    return "configure Codex project hooks and local safety workflow";
  }
  if (files.some((relPath) => relPath.startsWith("supabase/migrations/"))) {
    return "update database schema";
  }
  if (files.some((relPath) => relPath.startsWith("scripts/"))) {
    return "update project automation scripts";
  }
  if (files.some((relPath) => relPath.startsWith("src/"))) {
    return "update application behavior";
  }
  if (files.every((relPath) => isDocsFile(relPath))) {
    return "update project documentation";
  }
  return "record validated local changes";
}

function inferImpact(files) {
  if (files.some((relPath) => relPath.startsWith("supabase/migrations/"))) {
    return "database behavior or available columns may change";
  }
  if (files.some((relPath) => relPath.startsWith("src/"))) {
    return "application runtime behavior may change";
  }
  if (files.some((relPath) => relPath.startsWith("scripts/"))) {
    return "local automation behavior may change";
  }
  if (files.some((relPath) => relPath.startsWith(".codex/"))) {
    return "Codex local workflow behavior changes for trusted project sessions";
  }
  return "documentation or metadata only";
}

function inferRisk(files, deletions) {
  if (deletions.length) {
    return "high; deleted files are present and auto-commit is skipped";
  }
  if (files.some((relPath) => relPath.startsWith("supabase/migrations/"))) {
    return "medium; verify database migration order and rollback manually";
  }
  if (files.some((relPath) => relPath.startsWith("src/"))) {
    return "medium; verify affected UI and data flows";
  }
  return "low";
}

function maybeCommit({ baseline, branch, candidates, deletions, validation }) {
  if (!baseline) {
    console.log("[codex-hooks] Auto-commit skipped: no turn baseline was recorded.");
    return { ok: false, reason: "missing-baseline" };
  }

  if (branch === "main" || branch === "master") {
    console.log("[codex-hooks] Auto-commit skipped: protected branch.");
    return { ok: false, reason: "protected-branch" };
  }

  if (!validation.ok) {
    console.log("[codex-hooks] Auto-commit skipped: validation failed.");
    return { ok: false, reason: "validation-failed" };
  }

  if (deletions.length) {
    console.log("[codex-hooks] Auto-commit skipped: file deletions detected.");
    return { ok: false, reason: "deletions-detected" };
  }

  if (!candidates.length) {
    console.log("[codex-hooks] Auto-commit skipped: no candidate files.");
    return { ok: false, reason: "no-candidates" };
  }

  const add = runGit(root, ["add", "--", ...candidates]);
  if (!add.ok) {
    console.error(add.stderr || add.stdout);
    return { ok: false, reason: "git-add-failed" };
  }

  const staged = runGit(root, ["diff", "--cached", "--quiet"]);
  if (staged.status === 0) {
    return { ok: false, reason: "nothing-staged" };
  }

  const commitMessage = makeCommitMessage(candidates);
  const commit = runGit(root, ["commit", "-m", commitMessage], {
    maxBuffer: 1024 * 1024 * 16,
  });

  if (!commit.ok) {
    console.error(commit.stderr || commit.stdout);
    return { ok: false, reason: "git-commit-failed" };
  }

  console.log(commit.stdout.trim());
  return { ok: true, message: commitMessage };
}

function makeCommitMessage(files) {
  if (files.some((relPath) => relPath.startsWith(".codex/"))) {
    return "chore: configure Codex hooks";
  }
  if (files.some((relPath) => relPath.startsWith("supabase/migrations/"))) {
    return "chore: update database schema";
  }
  if (files.some((relPath) => relPath.startsWith("scripts/"))) {
    return "chore: update project scripts";
  }
  if (files.some((relPath) => relPath.startsWith("src/"))) {
    return "feat: update application behavior";
  }
  return "docs: update project documentation";
}
